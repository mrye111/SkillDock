// Local prototype QA. Uses the already-installed browser runtime; not needed to open the HTML.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('D:/node/node_global/node_modules/dembrandt/node_modules/playwright-core');
const output = path.join(__dirname, 'screenshots');
fs.mkdirSync(output, {recursive:true});
(async()=>{
  const browser = await chromium.launch({executablePath:'C:/Users/23167/AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe',headless:true});
  const page = await browser.newPage({viewport:{width:1600,height:1050},deviceScaleFactor:1});
  const errors=[]; const checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  const shot=async name=>{await page.waitForTimeout(450);await page.screenshot({path:path.join(output,name+'.png')});};
  const close=async()=>{await page.locator('#overlay-root [data-action=close]').first().click();await page.waitForTimeout(220);};
  const navigate=async hash=>{await page.locator(`a[data-page=${hash}]`).click();await page.waitForTimeout(180);};
  await page.goto('http://127.0.0.1:4176');
  await page.waitForTimeout(500);
  assert.equal(await page.locator('tbody tr').count(),8);
  await shot('01-library');
  await navigate('targets'); await shot('02-targets');
  assert.equal(await page.locator('.target-card').count(),4);
  assert.equal(await page.locator('input[type=checkbox]').count(),0);
  checks.push('Four configured destinations; no unsupported target toggles.');
  await navigate('history'); await shot('03-history');
  await navigate('settings'); await shot('04-settings');
  assert.equal(await page.locator('[data-action=save-rules]').isDisabled(),true);
  assert.equal(await page.locator('[data-action=save-backup]').isDisabled(),true);
  await page.locator('#rule-input').fill('**/*.log');
  await page.locator('[data-action=add-rule]').click();
  assert.equal(await page.locator('[data-action=save-rules]').isEnabled(),true);
  await page.locator('[data-action=save-rules]').click();
  await page.waitForTimeout(180);
  assert.equal(await page.locator('[data-action=save-rules]').isDisabled(),true);
  await page.locator('#retention-days').fill('14');
  await page.locator('[data-action=save-backup]').click();
  await page.waitForTimeout(180);
  assert.equal(await page.locator('#retention-days').inputValue(),'14');
  checks.push('Ignore rules and backup policy save independently through existing commands.');
  await navigate('library');
  await page.getByRole('tab').filter({hasText:'待同步'}).click();
  assert.equal(await page.locator('tbody tr').count(),2);
  await page.locator('#skill-search').fill('meeting');
  assert.equal(await page.locator('tbody tr').count(),1);
  await page.locator('#skill-search').fill('');
  await page.getByRole('tab').filter({hasText:'全部'}).click();
  checks.push('Matrix status filters and name/description search work.');
  await page.locator('[data-action=preview-selection]').click();
  await page.waitForSelector('.drawer');
  await shot('05-sync-preview');
  const plan=await page.evaluate(()=>window.SkillDockPrototype.currentPlan);
  assert.equal(plan.summary.executableCount,4);
  assert.equal(plan.summary.skipCount,1);
  assert.equal(await page.locator('.drawer input[type=checkbox]').count(),0);
  checks.push('Plan has four executable mappings and one skipped mapping; no unsupported plan selection editing.');
  await page.locator('[data-action=execute-plan]').click();
  await page.waitForSelector('.task-orbit');
  await shot('06-task-progress');
  await page.getByRole('heading',{name:'模拟任务已完成'}).waitFor({timeout:10000});
  const task=await page.evaluate(()=>window.SkillDockPrototype.task);
  assert.equal(task.counts.success,4); assert.equal(task.counts.skipped,1);
  await close();
  checks.push('Simulated progress finishes with success and skipped counts separated.');
  await page.locator('.cell-state.target_modified').click();
  await page.waitForSelector('.conflict-box');
  await shot('07-conflict');
  await page.locator('[data-choice=keep_target]').click();
  await page.waitForTimeout(180);
  const kept=await page.evaluate(()=>window.SkillDockPrototype.currentPlan);
  assert.equal(kept.summary.conflictCount,0);assert.equal(kept.summary.executableCount,0);
  await close();
  checks.push('Conflict choices update plan version and keep-target performs no write.');
  await navigate('history');
  await page.locator('.history-entry').first().click();
  await page.waitForSelector('.restore-checkbox');
  const recoverable=page.locator('.restore-checkbox:not(:disabled)');
  assert.ok(await recoverable.count()>0);
  await recoverable.first().check();
  await page.locator('[data-action=preview-restore]').click();
  await page.waitForSelector('.plan-item');
  const restore=await page.evaluate(()=>window.SkillDockPrototype.currentPlan);
  assert.equal(restore.operation,'restore');
  assert.equal(restore.summary.executableCount,1);
  await shot('08-restore-preview');
  await close();
  checks.push('History exposes available snapshots and creates a restore plan before execution.');
  await navigate('targets');
  await page.locator('[data-action=add-target]').click();
  await page.waitForSelector('#target-adapter');
  await page.locator('[data-action=save-target]').click();
  await page.waitForTimeout(350);
  assert.equal(await page.locator('.target-card').count(),5);
  checks.push('Custom destination creation uses save_target with custom name and path.');
  await navigate('library');
  await page.locator('[data-action=add-library]').click();
  await page.waitForSelector('#library-path');
  await page.locator('[data-action=save-library]').click();
  await page.waitForTimeout(1200);
  assert.equal(await page.getByRole('heading',{name:'这里还没有找到技能'}).count(),1);
  await shot('09-empty-library');
  const log=await page.evaluate(()=>window.SkillDockPrototype.commandLog);
  const registerIndex=log.findLastIndex(x=>x.name==='register_library');
  const sequence=log.slice(registerIndex).map(x=>x.name);
  assert.ok(sequence.indexOf('scan_library')<sequence.indexOf('get_library'));
  checks.push('New library follows register -> scan -> get, with a real empty-state design.');
  await page.reload();
  await page.waitForTimeout(500);
  await page.setViewportSize({width:1100,height:800});
  await shot('10-compact');
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  assert.equal(overflow,false);
  checks.push('1100 px window contains the layout; matrix scroll remains inside its panel.');
  await page.emulateMedia({reducedMotion:'reduce'});
  const reduced=await page.locator('.page').evaluate(el=>getComputedStyle(el).animationDuration);
  assert.ok(parseFloat(reduced)<0.01);
  checks.push('Reduced-motion preference disables spatial animations.');
  assert.deepEqual(errors,[]);
  const result={passed:checks.length,checks,pageErrors:errors,verifiedAt:new Date().toISOString()};
  fs.writeFileSync(path.join(__dirname,'verification.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
