def render_rule_block() -> str:
    return """## Selector 优先级

1. 语义 ID / role：`#firstName`、`page.get_by_role(...)`
2. 稳定属性：`[data-testid=...]`、`[placeholder=...]`、`[href*=...]`
3. 明确文本：`get_by_text(...)`、`:has-text(...)`
4. 避免：hash class、`:nth-child`、xpath 位置索引

## 等待和断言

- 导航后优先等待 `networkidle` 或具体元素可见。
- 断言使用 Playwright `expect(...)` 的自动重试能力。
- 不用固定 sleep 迁就时序。

## 测试设计红线

- 不删除或弱化断言来让测试通过。
- `expected` 不使用空字符串、`0` 或 `-` 作为迁就值。
- 文本断言优先包含或 regex，避免脆弱精确匹配。
"""


class HarnessInitializer:
    def __init__(self, project_root: Path, apply: bool) -> None:
        self.root = project_root.resolve()
        self.apply = apply
        self.ops: list[Operation] = []

    def rel(self, path: Path) -> str:
        try:
            return str(path.resolve().relative_to(self.root))
        except ValueError:
            return str(path)

    def record(self, action: str, path: Path, detail: str, destructive: bool = False) -> None:
        self.ops.append(Operation(action, path, detail, destructive))

    def ensure_dir(self, path: Path) -> None:
        target = self.root / path
        if target.exists():
            self.record("unchanged", target, "directory exists")
            return
        self.record("mkdir", target, "create directory")
        if self.apply:
            target.mkdir(parents=True, exist_ok=True)

    def write_managed_file(self, relative: Path, content: str) -> None:
        target = self.root / relative
        if target.exists():
            old = target.read_text(encoding="utf-8")
            if old == content:
                self.record("unchanged", target, "managed file already current")
                return
            if MANAGED_FILE_MARKER not in old:
                self.record(
                    "manual",
                    target,
                    "exists without init-harness marker; review before replacing",
                )
                return
            self.record("update", target, "update managed file")
        else:
            self.record("create", target, "create managed file")
        if self.apply:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")

    def upsert_block(self, relative: Path, name: str, content: str, style: str) -> None:
        target = self.root / relative
        begin, end, block = managed_block(name, content, style)
        if target.exists():
            old = target.read_text(encoding="utf-8")
            if begin in old and end in old:
                before, rest = old.split(begin, 1)
                _, after = rest.split(end, 1)
                prefix = before.rstrip()
                suffix = after.lstrip("\n")
                new = prefix
                if new:
                    new += "\n\n"
                new += block
                if suffix:
                    new += "\n" + suffix
                action = "update" if new != old else "unchanged"
                detail = "replace managed block" if action == "update" else "managed block current"
            else:
                prefix = "" if old.endswith("\n") else "\n"
                new = old + prefix + "\n" + block
                action = "update"
                detail = "append managed block"
        else:
            new = block
            action = "create"
            detail = "create file with managed block"

        self.record(action, target, detail)
        if self.apply and action != "unchanged":
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(new, encoding="utf-8")

    def copy_template_tree(self) -> None:
        for template in TEMPLATES_DIR.rglob("*"):
            if template.is_dir():
                continue
            relative = template.relative_to(TEMPLATES_DIR)
            target = self.root / relative
            content = template.read_text(encoding="utf-8")
            if target.exists():
                old = target.read_text(encoding="utf-8")
                if old == content:
                    self.record("unchanged", target, "template already current")
                    continue
                if MANAGED_FILE_MARKER not in old:
                    self.record(
                        "manual",
                        target,
                        "exists without init-harness marker; review before replacing",
                    )
                    continue
                self.record("update", target, "update managed template")
            else:
                self.record("create", target, "create managed template")
            if self.apply:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")

    def clean_demo_artifacts(self) -> None:
        candidates = [
            Path("page_map/testerhome"),
            Path("data/testerhome.yaml"),
            Path("tests/test_home.py"),
            Path("tests/test_search.py"),
        ]
        artifact_root = self.root / "artifacts"
        if artifact_root.exists():
            candidates.extend(
                p.relative_to(self.root)
                for p in artifact_root.iterdir()
                if p.is_dir() and "testerhome" in p.name.lower()
            )

        for relative in candidates:
            target = self.root / relative
            if not target.exists():
                continue
            if target.is_file():
                text = target.read_text(encoding="utf-8", errors="ignore")
                if "testerhome" not in text.lower() and "测试之家" not in text:
                    self.record("manual", target, "demo-like path but content is not clearly TesterHome")
                    continue
            self.record("delete", target, "remove known TesterHome demo artifact", destructive=True)
            if self.apply:
                if target.is_dir():
                    shutil.rmtree(target)
                else:
                    target.unlink()

    def sync(self, profile: dict[str, Any]) -> None:
        tests_dir = Path(path_value(profile, "paths", "tests_dir", "tests"))
        data_dir = Path(path_value(profile, "paths", "data_dir", "data"))
        page_map_dir = Path(path_value(profile, "paths", "page_map_dir", "page_map"))
        artifacts_dir = Path(path_value(profile, "paths", "artifacts_dir", "artifacts"))

        for directory in [
            tests_dir,
            data_dir,
            page_map_dir,
            artifacts_dir,
            Path(".claude/agents"),
            Path("scripts"),
        ]:
            self.ensure_dir(directory)

        self.copy_template_tree()
        self.write_managed_file(Path("pytest.ini"), render_pytest_ini(profile))
        self.write_managed_file(Path(".env.example"), render_env_example(profile))
        self.upsert_block(Path("CLAUDE.md"), "project-contract", render_claude_block(profile), "html")
        self.upsert_block(Path("conftest.py"), "fixtures", render_conftest_block(profile), "hash")
        self.upsert_block(
            Path("conftest.py"),
            "custom-auth-hooks",
            render_conftest_custom_block(),
            "hash",
        )
        self.upsert_block(Path(".gitignore"), "ignore-rules", render_gitignore_block(), "hash")
        self.upsert_block(
            Path("requirements.txt"),
            "python-deps",
            render_requirements_block(),
            "hash",
        )
        self.upsert_block(Path("rule.md"), "testing-rules", render_rule_block(), "html")
        self.clean_demo_artifacts()

    def print_plan(self) -> None:
        for op in self.ops:
            marker = "!" if op.destructive else "-"
            print(f"{marker} {op.action:9} {self.rel(op.path)} :: {op.detail}")

        summary: dict[str, int] = {}
        for op in self.ops:
            summary[op.action] = summary.get(op.action, 0) + 1
        print("\nSummary:")
        for action in sorted(summary):
            print(f"  {action}: {summary[action]}")

        manual = [op for op in self.ops if op.action == "manual"]
        if manual:
            print("\nManual attention required:")
            for op in manual:
                print(f"  - {self.rel(op.path)}: {op.detail}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", default=".", help="Target project root")
    parser.add_argument("--plan", action="store_true", help="Show plan only")
    parser.add_argument("--apply", action="store_true", help="Apply changes")
    args = parser.parse_args(argv)

    if args.plan and args.apply:
        parser.error("choose only one of --plan or --apply")

    project_root = Path(args.project_root).resolve()
    profile_path = project_root / PROFILE_NAME

    if not project_root.exists():
        print(f"Project root does not exist: {project_root}", file=sys.stderr)
        return 2

    if not profile_path.exists():
        profile_path.write_text(profile_draft(project_root), encoding="utf-8")
        print(f"Created draft profile: {profile_path}")
        print("Edit harness.project.yaml, then rerun init-harness in plan/apply mode.")
        return 0

    try:
        profile = load_profile(profile_path)
    except Exception as exc:  # noqa: BLE001
        print(f"Failed to read {profile_path}: {exc}", file=sys.stderr)
        return 2

    initializer = HarnessInitializer(project_root, apply=args.apply)
    initializer.sync(profile)
    initializer.print_plan()

    if not args.apply:
        print("\nPlan only. Rerun with --apply to write changes.")
    else:
        print("\nApplied changes.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
